#!/bin/sh
# Prints the Homebrew formula of a release, from the archives' .sha256 files.
# Usage: packaging/homebrew-formula.sh <version> <folder with liberarr-<target>.tar.gz.sha256>
set -eu

version=$1
dir=$2
url="https://github.com/hocinehacherouf/liberarr/releases/download/v$version"

# The hash of one target; stops when the file is missing or not a SHA-256.
hash() {
  value=$(cut -d ' ' -f 1 <"$dir/liberarr-$1.tar.gz.sha256")
  case "$value" in
    *[!0-9a-f]* | "") echo "bad hash for $1" >&2; exit 1 ;;
  esac
  [ ${#value} -eq 64 ] || { echo "bad hash for $1" >&2; exit 1; }
  echo "$value"
}

mac_arm=$(hash aarch64-apple-darwin)
mac_intel=$(hash x86_64-apple-darwin)
linux_arm=$(hash aarch64-unknown-linux-gnu)
linux_intel=$(hash x86_64-unknown-linux-gnu)

cat <<EOF
# Generated by packaging/homebrew-formula.sh in hocinehacherouf/liberarr. Do not edit by hand.
class Liberarr < Formula
  desc "Transcripts, summaries and notes from Plaud recordings, with any AI provider"
  homepage "https://github.com/hocinehacherouf/liberarr"
  license "MIT"

  on_macos do
    on_arm do
      url "$url/liberarr-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$url/liberarr-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$url/liberarr-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$url/liberarr-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "liberarr"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/liberarr --version")
  end
end
EOF
